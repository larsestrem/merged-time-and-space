/* "in 8 hours, 24 minutes" — the element that makes this a countdown site */
function mnCountLabel(ms){
  if(ms<=0) return 'happening now';
  var m=Math.floor(ms/60000), d=Math.floor(m/1440), h=Math.floor(m%1440/60), mi=m%60;
  function u(n,w){ return n+' '+w+(n===1?'':'s'); }
  if(d>0) return 'in '+u(d,'day')+', '+u(h,'hour');
  if(h>0) return 'in '+u(h,'hour')+', '+u(mi,'minute');
  return 'in '+u(mi,'minute');
}
