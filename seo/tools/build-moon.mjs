const tzDateLong = (ms, tz) => { try { return new Intl.DateTimeFormat("en-US", { timeZone: tz, month: "long", day: "numeric", year: "numeric" }).format(new Date(ms)); } catch (e) { return "—"; } };
/* epoch of the city's local midnight for the day containing `ms` (minute
 * precision — moonTimes samples hourly, so seconds are noise) */
function tzDayStart(ms, tz) {
  const p = new Intl.DateTimeFormat("en-GB", { timeZone: tz, hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(new Date(ms)).split(":");
  return ms - (+p[0] * 3600 + +p[1] * 60) * 1000 - (ms % 60000);
}

