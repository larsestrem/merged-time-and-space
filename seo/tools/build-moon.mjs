/* the 30-day phase strip, baked; the client redraws it from the visitor's today */
/* `south` mirrors every glyph, because the moon is seen upside down from the
 * southern hemisphere. The hero glyph on a city page has always been mirrored;
 * the 30-day strip was baked un-mirrored and only corrected when the client
 * repainted it, so a Sydney or Cape Town visitor saw the strip flip a moment
 * after load — and a crawler saw the wrong version. */
function stripHtml(from, south = false) {
  const day0 = Date.UTC(from.getUTCFullYear(), from.getUTCMonth(), from.getUTCDate(), 12);
  const primaries = new Map();
  for (const p of yearPhases(from.getUTCFullYear()).concat(yearPhases(from.getUTCFullYear() + 1))) {
    const d = new Date(p.t);
    primaries.set(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()), p.kind);
  }
  let out = "";
  for (let i = 0; i < 30; i++) {
    const t = day0 + i * 86400000;
    const il = moonIllum(t);
    const kind = primaries.get(Date.UTC(new Date(t).getUTCFullYear(), new Date(t).getUTCMonth(), new Date(t).getUTCDate()));
    out += `<div class="mn-day${kind !== undefined ? " is-primary" : ""}"><span class="mn-day-g">${moonGlyph(il.fraction, il.waxing, 15, south)}</span>` +
      `<span class="mn-day-d">${esc(utcShort(t))}</span>` +
      `<span class="mn-day-p">${kind !== undefined ? esc(primaryName(kind)) : Math.round(il.fraction * 100) + "%"}</span></div>`;
  }
  return out;
}

/* ===========================================================================
 * /moon/calendar/ — the month grid
 *
 * The site already had two ways to read the moon over time, and both are
 * LISTS of the four primary phases: /moon/<year>/ and /moon/full-moon-calendar/.
 * Neither answers "what does the moon look like on the 14th", which is what a
 * calendar is for. This is the grid: one cell per day, every day drawn, with
 * the primary phases called out where they land.
 *
 * Dates are a real problem here and worth being explicit about. A phase is one
 * instant worldwide, so which CALENDAR DAY it falls on depends on where you
 * are — a full moon at 04:18 UTC on the 28th is the evening of the 27th in
 * Los Angeles. The baked grid is UTC (crawlable, and the same convention the
 * year tables use); on load the browser re-buckets every phase into the
 * visitor's own dates, so what they read is right for where they are.
 * ========================================================================= */
export const MONTH_NAMES = ["January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December"];
export const monthSlug = (y, m) => `${MONTH_NAMES[m].toLowerCase()}-${y}`;
export const CAL_MONTHS = [];
for (const y of MOON_YEARS) for (let m = 0; m < 12; m++) CAL_MONTHS.push([y, m]);
/* the month slugs as a flat list — build-inline and build-sitemap both need
 * the page paths, and neither should have to re-derive them */
export const CAL_SLUGS = CAL_MONTHS.map(([y, m]) => monthSlug(y, m));

/* every primary phase in a year and its neighbours, keyed by UTC date, so a
 * grid that spills into the previous/next month still labels correctly */
function primariesByUtcDate(year) {
  const map = new Map();
  for (const p of yearPhases(year - 1).concat(yearPhases(year), yearPhases(year + 1))) {
    const d = new Date(p.t);
    map.set(`${d.getUTCFullYear()}-${d.getUTCMonth()}-${d.getUTCDate()}`, p);
  }
  return map;
}
const DOW = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
/* the grid itself. Weeks run Sunday→Saturday; days outside the month are
 * rendered but dimmed, so the shape of the month reads at a glance. */
function calGrid(year, month, prim) {
  const first = new Date(Date.UTC(year, month, 1));
  const lead = first.getUTCDay();
  const days = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();
  const cells = [];
  for (let i = 0; i < lead; i++) {
    const t = Date.UTC(year, month, 1 - (lead - i), 12);
    cells.push([t, false]);
  }
  for (let d = 1; d <= days; d++) cells.push([Date.UTC(year, month, d, 12), true]);
  while (cells.length % 7) {
    const t = Date.UTC(year, month, days + 1 + (cells.length - lead - days), 12);
    cells.push([t, false]);
  }
  const todayKey = `${NOW.getUTCFullYear()}-${NOW.getUTCMonth()}-${NOW.getUTCDate()}`;
  const head = DOW.map((d) => `<div class="mn-cal-dow" aria-hidden="true">${d}</div>`).join("");
  const body = cells.map(([t, inMonth]) => {
    const d = new Date(t);
    const key = `${d.getUTCFullYear()}-${d.getUTCMonth()}-${d.getUTCDate()}`;
    const p = prim.get(key);
    const il = moonIllum(t);
    const iso = `${d.getUTCFullYear()}-${String(d.getUTCMonth() + 1).padStart(2, "0")}-${String(d.getUTCDate()).padStart(2, "0")}`;
    const cls = ["mn-cal-day"];
    if (!inMonth) cls.push("is-out");
    if (p) cls.push("is-primary");
    if (key === todayKey) cls.push("is-today");
    return `<a class="${cls.join(" ")}" href="/moon/?date=${iso}" data-mn-cal="${iso}" aria-label="${esc(utcDate(t))} — ${p ? esc(primaryName(p.kind)) : Math.round(il.fraction * 100) + "% illuminated"}">`
      + `<span class="mn-cal-n">${d.getUTCDate()}</span>`
      + `<span class="mn-cal-g">${moonGlyph(il.fraction, il.waxing, 15)}</span>`
      + `<span class="mn-cal-p">${p ? esc(primaryName(p.kind)) : Math.round(il.fraction * 100) + "%"}</span></a>`;
  }).join("");
  return `<div class="mn-cal" id="mn-cal">${head}${body}</div>`;
}

