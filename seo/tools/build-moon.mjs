/* /moon/state/<state>/ — the same city lists the /sun/ state hubs use, so the
 * two families pair 1:1 and interlink. */
function buildState(s) {
  const cities = s.cities;
  /* Grouped by county, counties A-Z and cities A-Z inside them. The old page
     was one flat blob in population order, which is unusable once a state runs
     to 200 cities. Counties come from city-counties.json; anything without one
     is listed under "Other cities" rather than filed under a guess. */
  const byCounty = new Map();
  const orphans = [];
  for (const ct of cities.slice().sort((a, b) => a.city.localeCompare(b.city))) {
    const county = CITY_COUNTY[ct.slug];
    if (!county) { orphans.push(ct); continue; }
    if (!byCounty.has(county)) byCounty.set(county, []);
    byCounty.get(county).push(ct);
  }
  const counties = [...byCounty.keys()].sort((a, b) => a.localeCompare(b));
  const group = (name, list) => `      <div class="mn-county">
        <h3 class="mn-county-h">${esc(name)}</h3>
        <p class="timer-presets">
${list.map((ct) => `          <a class="chip" href="/moon/${ct.slug}/">${esc(ct.city)}</a>`).join("\n")}
        </p>
      </div>`;
  const groups = [
    ...counties.map((c) => group(c, byCounty.get(c))),
    ...(orphans.length ? [group("Other cities", orphans)] : []),
  ].join("\n");

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
${head({
    title: `Moonrise and Moonset Times in ${s.state}`,
    desc: `Tonight's moonrise and moonset for ${cities.length} ${s.state} cities — local times, direction, phase and a 7-day outlook for each.`,
    path: `/moon/state/${s.slug}/`,
    ld: `\n<script type="application/ld+json">${breadcrumbLD(SITE, [{ name: "Time and Space Science", url: "/" }, { name: "Moon", url: "/moon/" }, { name: s.state, url: `/moon/state/${s.slug}/` }])}</script>`,
  })}
</head>
<body>
<div class="wrap">
  ${brand({ crumb: { slug: "moon", url: "/moon/" }, page: { label: s.slug, url: `/moon/state/${s.slug}/` } })}
  <h1>Moonrise &amp; Moonset in ${esc(s.state)}</h1>
  <p class="sub">Pick a city for tonight's moonrise and moonset, the direction to look, the current phase and the next 7 days — all in local time. Grouped by county, A–Z.</p>
  <div class="card">
${groups}
  </div>
  <div class="card tool-about">
    <h2>More for ${esc(s.state)}</h2>
    <p><a data-xlink="sun" href="/sun/state/${s.slug}/">Sunrise &amp; sunset across ${esc(s.state)}</a> · <a href="/moon/">today's moon phase</a> · <a href="/moon/full-moon-calendar/">full moon calendar</a>.</p>
  </div>
  <p class="footer"><a href="/terms">Terms</a> · <a href="/privacy">Privacy</a></p>
</div>
</body>
</html>
`;
  write(`moon/state/${s.slug}`, html);
}


