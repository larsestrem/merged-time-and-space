export const PARTS = SPEC.slice();
export const SECTIONS = [...new Set(SPEC.map(([, s]) => s))];

const read = (f) => readFileSync(join(PARTS_DIR, f), "utf8");

/** Every part, in cascade order — byte-identical to the old style.css. */
export const fullCss = () => SPEC.map(([f]) => read(f)).join("\n");

/** Only the parts whose section is wanted, still in cascade order. */
export function composeCss(sections) {
  const want = new Set(sections);
  return SPEC.filter(([, sec]) => want.has(sec)).map(([f]) => read(f)).join("\n");
}

/** Throws unless the parts still reassemble into exactly `expected`. */
export function assertLossless(expected) {
  const got = fullCss();
  if (got !== expected) {
    const at = [...got].findIndex((c, i) => c !== expected[i]);
    throw new Error(`css parts no longer reassemble into style.css (first difference at char ${at})`);
  }
  const onDisk = readdirSync(PARTS_DIR).filter((f) => f.endsWith(".css")).sort().join();
  const named = SPEC.map(([f]) => f).sort().join();
  if (onDisk !== named) throw new Error(`assets/css/parts holds ${onDisk} but the manifest lists ${named}`);
}


/* ------------------------------------------------------------------ gate ---
 * WHICH SECTIONS COULD A PIECE OF MARKUP ACTUALLY USE?
 *
 * The probes in build-inline are hand-written regexes, and a wrong one is
 * invisible: the page renders, just unstyled somewhere nobody looked. This
 * derives the answer from the CSS itself instead — a section is needed when
 * one of its selectors could match, i.e. every class/id token in that single
 * selector is present in the markup. Compound selectors are respected, so
 * ".mc-widget .btn" needs BOTH, not just ".btn".
 *
 * build-inline asserts probes ⊇ this for every page it writes. Over-inclusion
 * is fine (a probe may be broader than strictly necessary); under-inclusion
 * fails the build. Element-only selectors (`body`, `h2`) are ignored — they
 * carry no token to test and always live in `core` anyway. */
const selCache = new Map();
function selectorsOf(file) {
  if (selCache.has(file)) return selCache.get(file);
  const css = read(file).replace(/\/\*[\s\S]*?\*\//g, " ");
  const out = [];
  for (const m of css.matchAll(/([^{}]+)\{/g)) {
    const prelude = m[1].trim();
    if (prelude.startsWith("@")) continue;
    for (const sel of prelude.split(",")) {
      const toks = [...sel.matchAll(/[.#]([A-Za-z_][\w-]*)/g)].map((x) => x[1]);
      if (toks.length) out.push(toks);
    }
  }
  selCache.set(file, out);
  return out;
}

/** class + id tokens used by a page's MARKUP (its own <style>/<script> ignored) */
export function markupTokens(html) {
  const body = html.replace(/<style[\s\S]*?<\/style>/gi, " ").replace(/<script[\s\S]*?<\/script>/gi, " ");
  const t = new Set();
  for (const m of body.matchAll(/\sclass="([^"]*)"/g)) for (const c of m[1].split(/\s+/)) if (c) t.add(c);
  for (const m of body.matchAll(/\sid="([^"]*)"/g)) t.add(m[1]);
  return t;
}

/** Sections whose CSS this markup could actually use. `core` is unconditional
 *  and `themes` is never selected, so neither is reported. */
export function sectionsNeeded(html) {
  const tok = markupTokens(html);
  const need = new Set();
  for (const [file, sec] of SPEC) {
    if (sec === "core" || sec === "themes" || need.has(sec)) continue;
    for (const s of selectorsOf(file)) {
      if (s.every((x) => tok.has(x))) { need.add(sec); break; }
    }
  }
  return need;
}

