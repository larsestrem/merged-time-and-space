/* css-parts.mjs — the stylesheet as an ordered list of section files.
 *
 * assets/css/style.css was one 132KB monolith that every tool page inlined
 * whole: a timer page carried the alarm clock's 20KB, the tide tool's 11KB and
 * the home dashboard's 7KB for nothing. The source of truth is now
 * assets/css/parts/NN-name.css, each tagged with the SECTION it belongs to;
 * build-inline gives a page only the sections it actually renders.
 *
 * TWO RULES MAKE THIS SAFE, both enforced below rather than trusted:
 *
 * 1. Parts are emitted in numeric filename order — the order they were cut from
 *    the original file. What a page gets is a SUBSEQUENCE of the old cascade,
 *    never a reordering, so a rule that won before still wins.
 * 2. fullCss() must equal the old monolith byte for byte. assertLossless()
 *    checks it, so "nothing was dropped" is a test, not a claim.
 *
 * WHY THE CORE SLIVERS (04, 06, 09, 18): a handful of rules sit inside a widget's block
 * but are shared far beyond it — .tool-msg looks like timer furniture yet the
 * tide pages style their error line with it, and .timer-presets/.chip sit in the
 * tides search block yet every chip grid on the site uses them. A first pass
 * that shipped them with their neighbours broke chip layout on the sun pages,
 * the accent colour on tide errors, .tool-about spacing on the alarm and world
 * clock, and — worst — left the timer's Edit dialog completely unstyled, because
 * it reuses the alarm clock's .ac-dialog/.ac-form. Each is cut out IN PLACE as
 * its own `core` part, so the emitted order is untouched.
 *
 * Adding CSS: put it in the part for its section. A new section needs a new
 * numbered part plus an entry in SECTION_PROBES (build-inline.mjs), which is
 * what decides whether a page gets it.
 *
 * 01-themes.css is GENERATED by build-themes.mjs. style.css is generated too —
 * build-css.mjs folds the parts back into it, because the external <link>
 * fallback and social-card.mjs both still read that single file.
 */
